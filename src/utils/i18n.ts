const LANG_STORAGE_KEY = 'sliding_puzzle_lang';

export function getSavedLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && ['en', 'es', 'pt', 'fr', 'de', 'zh'].includes(saved)) {
      return saved as Language;
    }
    // Auto-detect browser language if available
    const browserLang = navigator.language.slice(0, 2).toLowerCase();
    if (['en', 'es', 'pt', 'fr', 'de', 'zh'].includes(browserLang)) {
      return browserLang as Language;
    }
  } catch (e) {
    console.warn('Could not read language preference:', e);
  }
  return 'en';
}

export function saveLanguage(lang: Language): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {
    console.warn('Could not save language preference:', e);
  }
}
